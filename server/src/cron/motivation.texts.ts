/** Сколько текстов в цикле. */
export const MOTIVATION_CYCLE = 30;

/** Текст для дня цикла (1-based). После последнего дня цикл повторяется. */
export function motivationForDay(context: MotivationContext, day: number): MotivationPush {
  const texts = buildMotivationTexts(context);
  const index = (((day - 1) % texts.length) + texts.length) % texts.length;
  return texts[index];
}
