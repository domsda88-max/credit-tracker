/** 2 839 177 ₽ */
function money(value: number): string {
  return `${Math.round(value).toLocaleString('ru-RU')} ₽`;
}

/** 53,9% */
function pct(value: number): string {
  return `${value.toLocaleString('ru-RU', { maximumFractionDigits: 1 })}%`;
}

/** «июля 2044» — родительный падеж. */
function monthYear(date: Date | null): string | null {
  if (!date) return null;
  return `${MONTHS[date.getUTCMonth()]} ${date.getUTCFullYear()}`;
}

/** «к июлю 2044». */
function monthYearTo(date: Date | null): string | null {
  if (!date) return null;
  return `к ${MONTHS_TO[date.getUTCMonth()]} ${date.getUTCFullYear()}`;
}

/** «в июле 2044». */
function monthYearIn(date: Date | null): string | null {
  if (!date) return null;
  return `в ${MONTHS_IN[date.getUTCMonth()]} ${date.getUTCFullYear()}`;
}

/** «40 000 ₽ до 28-го числа» */
function replenish(c: MotivationContext): string {
  const card = c.freezeCards[0];
  if (!card || !card.replenishSum) return 'сумму обновления периода';
  const day = card.replenishDay ? ` до ${card.replenishDay}-го числа` : '';
  return `${money(card.replenishSum)}${day}`;
}

/** Название самого дорогого долга или нейтральная подстановка. */
function topName(c: MotivationContext): string {
  return c.mostExpensive?.name ?? 'самая дорогая кредитка';
}

function topRate(c: MotivationContext): string {
  return c.mostExpensive ? pct(c.mostExpensive.rate) : 'высокий процент';
}

function topSentence(c: MotivationContext): string {
  if (!c.mostExpensive) return 'Твой самый дорогой долг';
  return `${c.mostExpensive.name} под ${pct(c.mostExpensive.rate)}`;
}

