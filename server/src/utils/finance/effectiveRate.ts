/**
 * Эффективная ставка для расчётов.
 *
 * Если кредитка «заморожена» (в цикле заморозки 🧊), проценты не начисляются —
 * значит в графике и прогнозах она считается как 0% годовых. Как только
 * пользователь снимает заморозку, возвращается реальная ставка.
 *
 * Для всех остальных кредитов ставка не меняется.
 */
export function effectiveAnnualRate(annualRate: number, frozen: boolean): number {
  return frozen ? 0 : annualRate;
}
